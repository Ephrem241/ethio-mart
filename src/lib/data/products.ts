// Every seed product shares one literal TIMESTAMP above, which would make
// "Newest" sort functionally correct but invisibly so. Stagger created_at
// deterministically (pure hash of id, no Math.random — stays hydration-safe)
// so the sort is demonstrably real without hand-editing 32 literals.
function hashString(value: string): number {
  let hash = 0
  for (let i = 0; i < value.length; i++) {
    hash = (hash * 31 + value.charCodeAt(i)) >>> 0
  }
  return hash
}

